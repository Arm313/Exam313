// frontend/generate-font.js
const fs = require('fs');
const path = require('path');

const fontPath = path.join(__dirname, 'public', 'fonts', 'NotoSansArmenian.ttf');

if (!fs.existsSync(fontPath)) {
  console.error('❌ Font not found at:', fontPath);
  console.error('Download it first from:');
  console.error('https://github.com/google/fonts/raw/main/ofl/notosansarmenian/NotoSansArmenian%5Bwdth%2Cwght%5D.ttf');
  process.exit(1);
}

const base64 = fs.readFileSync(fontPath).toString('base64');
console.log('Font size:', (base64.length / 1024).toFixed(2), 'KB (base64)');

const output = `// Auto-generated by generate-font.js\n// Noto Sans Armenian (base64)\n\nexport const NOTO_ARMENIAN_BASE64 = '${base64}';\n`;
const outPath = path.join(__dirname, 'src', 'utils', 'fonts.js');

// Ensure dir exists
const dir = path.dirname(outPath);
if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

fs.writeFileSync(outPath, output);
console.log('✅ Written to', outPath);